'use strict';

// Cross-check the zip-derived entries against the project catalog mirrored in
// README.md between BEGIN/END markers, then merge the two views.
//
// Contract:
//   * Only the text between the markers is managed; everything outside the
//     markers is preserved byte-for-byte.
//   * Missing markers: the block is appended exactly once. Repeated runs are
//     idempotent and never append it again.
//   * Duplicate names: the first occurrence wins and a warning is recorded.
//   * When the central directory is damaged, zipEntries is null and the README
//     block becomes the source of truth (degraded mode).

const fs = require('fs');
const path = require('path');
const {
  atomicWriteSync,
  cleanupStale,
} = require('./atomicWrite');

const BEGIN = '<!-- BEGIN PROJECT CATALOG -->';
const END = '<!-- END PROJECT CATALOG -->';
const BLOCK_TITLE = '## Project Catalog';
const BLOCK_NOTE =
  '> Generated by `tools/catalogd.js`. Do not edit between the markers; rebuild with `POST /rebuild`.';

const DEFAULT_MAX_ENTRIES = 10000;
const DEFAULT_MAX_NAME = 200;

// Match the managed block including the trailing newline of the END line.
const BLOCK_PATTERN = new RegExp(
  BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
    '[\\s\\S]*?' +
    END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
    '(?:\r\n|\n|\r)?'
);

function detectEol(text) {
  if (text.includes('\r\n')) return '\r\n';
  if (text.includes('\n')) return '\n';
  if (text.includes('\r')) return '\r';
  return process.platform === 'win32' ? '\r\n' : '\n';
}

function stripEol(line) {
  return line.replace(/\r$/, '');
}

// Read only the names managed between the markers. Returns null when the
// markers do not exist; throws when exactly one marker is present.
function parseReadmeEntries(readmeText) {
  const beginIndex = readmeText.indexOf(BEGIN);
  const endIndex = readmeText.indexOf(END);

  if (beginIndex === -1 && endIndex === -1) {
    return { present: false, entries: [], block: null };
  }
  if (beginIndex === -1 || endIndex === -1 || endIndex < beginIndex) {
    throw new Error(
      'README markers are malformed: expected a matched BEGIN/END pair'
    );
  }

  const match = readmeText.match(BLOCK_PATTERN);
  if (!match) {
    throw new Error('README markers are malformed: managed block unreadable');
  }
  const block = match[0];
  const inner = readmeText.slice(beginIndex + BEGIN.length, endIndex);
  const names = [];
  for (const rawLine of inner.split(/\r\n|\n|\r/)) {
    const line = rawLine.trim();
    const entryMatch = line.match(/^-\s+\[([^\]]+)\]\s*$/);
    if (entryMatch) names.push(entryMatch[1]);
  }
  return { present: true, entries: names, block };
}

function truncateName(name, maxName, warnings) {
  if (name.length <= maxName) return name;
  warnings.push(
    `entry name too long (${name.length} > ${maxName}) truncated: "${name.slice(0, 40)}"`
  );
  return `${name.slice(0, Math.max(1, maxName - 1))}~`;
}

function renderBlock(names, eol) {
  const lines = [BEGIN, BLOCK_TITLE, '', BLOCK_NOTE, ''];
  for (const name of names) lines.push(`- [${name}]`);
  lines.push(END);
  return lines.join(eol) + eol;
}

// Append the block once, keeping every existing byte intact.
function appendBlock(readmeText, block, eol) {
  if (readmeText.length === 0) return block;
  // Existing bytes are never rewritten. If the file already ends with a blank
  // line the block starts directly; otherwise exactly one blank line is added.
  if (/(?:\r\n|\n|\r){2,}$/.test(readmeText)) {
    return readmeText + block;
  }
  if (/(?:\r\n|\n|\r)$/.test(readmeText)) {
    return readmeText + eol + block;
  }
  return readmeText + eol + eol + block;
}

// Merge zip entries and README entries with first-occurrence-wins semantics.
// Zip order leads; README-only entries follow so a damaged central directory
// degrades to the last README snapshot.
function mergeEntries(zipEntries, readmeNames, options, warnings) {
  const maxEntries = options.maxEntries ?? DEFAULT_MAX_ENTRIES;
  const maxName = options.maxName ?? DEFAULT_MAX_NAME;
  const merged = [];
  // Names are the stable catalog identity (readCentral truncates them first),
  // so a README mirror round-trip matches instead of looking like a new entry.
  const seen = new Set();
  let duplicateCount = 0;
  let ignoredOverCap = 0;

  const consider = (displayName, key) => {
    if (seen.has(key)) {
      duplicateCount += 1;
      warnings.push(
        `duplicate entry kept first occurrence: "${displayName}"`
      );
      return;
    }
    if (merged.length >= maxEntries) {
      ignoredOverCap += 1;
      return;
    }
    seen.add(key);
    merged.push(truncateName(displayName, maxName, warnings));
  };

  if (zipEntries) {
    // readCentral feeds unique, already-truncated entries and has warned about
    // zip-side duplicates/truncation; the guard also covers callers feeding
    // raw entries directly (e.g. the self-tests).
    for (const entry of zipEntries) {
      consider(entry.name, entry.name);
    }
  }
  for (const name of readmeNames) {
    // README mirrors the same (possibly truncated) names the zip produced.
    if (seen.has(name)) continue;
    consider(name, name);
  }

  if (ignoredOverCap > 0) {
    warnings.push(
      `entry limit reached (${maxEntries}); ${ignoredOverCap} further entry/entries ignored, not crashed`
    );
  }
  return { entries: merged, duplicateCount, ignoredOverCap };
}

function crossCheck(zipEntries, readmeNames) {
  const conflicts = [];
  if (!zipEntries) {
    return {
      conflicts,
      onlyInZip: [],
      onlyInReadme: readmeNames.slice(),
      matched: 0,
    };
  }
  const zipNames = new Set(zipEntries.map((entry) => entry.name));
  const readmeSet = new Set(readmeNames);

  for (const name of zipEntries.map((entry) => entry.name)) {
    if (!readmeSet.has(name)) {
      conflicts.push({ name, presentIn: 'zip' });
    }
  }
  for (const name of readmeNames) {
    if (!zipNames.has(name)) {
      conflicts.push({ name, presentIn: 'readme' });
    }
  }
  return {
    conflicts,
    onlyInZip: conflicts.filter((c) => c.presentIn === 'zip').map((c) => c.name),
    onlyInReadme: conflicts.filter((c) => c.presentIn === 'readme').map((c) => c.name),
    matched: zipNames.size - conflicts.filter((c) => c.presentIn === 'zip').length,
  };
}

// Core routine with no file IO. Exported for the self-tests.
function reconcile(readmeText, zipResult, options = {}) {
  const warnings = [];
  const notices = [];
  const degraded = zipResult === null;
  if (degraded) {
    warnings.push(
      'central directory unreadable: degraded to README catalog as source of truth'
    );
  }

  const parsed = parseReadmeEntries(readmeText);
  let readmeNames = parsed.entries;
  let readmeChanged = false;

  const { entries, duplicateCount, ignoredOverCap } = mergeEntries(
    degraded ? null : zipResult.entries,
    readmeNames,
    options,
    warnings
  );

  if (!degraded && Array.isArray(zipResult.warnings)) {
    warnings.push(...zipResult.warnings);
  }

  // Cross-check is only meaningful when the README already carried a managed
  // block. A first-ever append cannot conflict with a snapshot that did not
  // exist.
  const check =
    parsed.present || degraded
      ? crossCheck(degraded ? null : zipResult.entries, readmeNames)
      : { conflicts: [], onlyInZip: [], onlyInReadme: [], matched: entries.length };

  let nextReadme = readmeText;
  const eol = detectEol(readmeText);
  if (!parsed.present) {
    const block = renderBlock(entries, eol);
    nextReadme = appendBlock(readmeText, block, eol);
    readmeChanged = true;
    readmeNames = entries.slice();
    notices.push('README catalog markers were missing; block appended once');
  } else {
    const nextBlock = renderBlock(entries, eol);
    if (nextBlock !== parsed.block) {
      nextReadme = readmeText.replace(BLOCK_PATTERN, nextBlock);
      readmeChanged = true;
    }
  }

  return {
    entries,
    readmeText: nextReadme,
    readmeChanged,
    warnings,
    notices,
    conflicts: check.conflicts,
    onlyInZip: check.onlyInZip,
    onlyInReadme: check.onlyInReadme,
    matched: check.matched,
    degraded,
    stats: {
      readmeEntries: readmeNames.length,
      duplicates: duplicateCount,
      ignoredOverCap,
    },
  };
}

// Read README.md, reconcile, and atomically rewrite it only when something
// changed. zipResult is null when the caller detected central-directory
// corruption.
function mergeReadme(readmePath, zipResult, options = {}) {
  cleanupStale(path.resolve(readmePath));
  let readmeText;
  try {
    readmeText = fs.readFileSync(readmePath, 'utf8');
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
    readmeText = '';
  }

  const result = reconcile(readmeText, zipResult, options);
  if (result.readmeChanged && result.readmeText !== readmeText) {
    atomicWriteSync(readmePath, result.readmeText);
  }
  return result;
}

module.exports = {
  mergeReadme,
  reconcile,
  parseReadmeEntries,
  renderBlock,
  appendBlock,
  crossCheck,
  mergeEntries,
  BEGIN,
  END,
  DEFAULT_MAX_ENTRIES,
  DEFAULT_MAX_NAME,
};
